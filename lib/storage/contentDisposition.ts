// Единая сборка заголовка Content-Disposition для всех трёх мест, которые
// отдают файл на скачивание (файл вики, ZIP папки/коллекции, дамп БД).
// Раньше каждое собирало заголовок само: два — через локальную копию
// encodeAsciiFallback, третье (скачивание бэкапа) вставляло имя вообще как
// есть. Разъехавшиеся копии одной и той же защиты — как раз тот случай,
// когда третья про неё просто забыла.
//
// Что именно вычищается из ASCII-имени и почему:
//   - всё вне \x20-\x7E — управляющие символы и не-ASCII; перевод строки
//     здесь означал бы инъекцию нового заголовка в ответ;
//   - кавычка и обратный слэш — они попадают в разрешённый диапазон, но
//     закрывают/экранируют параметр filename="..." и ломают разбор.
// Настоящее (в т.ч. кириллическое) имя уезжает в filename* по RFC 5987 —
// современные браузеры берут именно его, а filename остаётся запасным.
export function attachmentHeader(fileName: string): string {
  const ascii = fileName.replace(/[^\x20-\x7E]/g, "_").replace(/["\\]/g, "_") || "file";
  return `attachment; filename="${ascii}"; filename*=UTF-8''${encodeURIComponent(fileName)}`;
}
