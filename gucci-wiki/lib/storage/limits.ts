// Единый лимит на загрузку файла в бакет (R01) — переиспользуется всеми
// загрузочными роутами (/api/upload, /api/files/upload). Логотип в /settings
// живёт по своему более строгому лимиту (2 МБ, lib/settings/logo.ts) — это
// не противоречит общему правилу, просто более узкое.
//
// Почему 50 МБ, а не 200, как было до QA-прогона 3: тело запроса
// буферизуется в памяти минимум трижды — `request.formData()` собирает весь
// multipart, потом `file.arrayBuffer()`, потом `Buffer.from(bytes)` внутри
// `uploadFile`. При `mem_limit: 350m` у контейнера `app` загрузка 220 МБ
// живым тестом упёрлась в потолок памяти, процесс умер и контейнер
// перезапустился — то есть один легитимный большой файл ронял всю вику для
// всех. 50 МБ × 3 копии + базовые ~140 МБ Next.js укладываются в 350 МБ с
// запасом. Поднять лимит обратно можно двумя путями, оба — осознанное
// решение владельца: либо увеличить `mem_limit` контейнера `app` (тогда
// считать по формуле «лимит × 3 + 150 МБ»), либо перейти на потоковую
// загрузку в S3 (`@aws-sdk/lib-storage`, новая зависимость) — тогда память
// перестаёт зависеть от размера файла.
//
// ВАЖНО: значение обязано совпадать с `client_max_body_size` в обоих
// nginx-шаблонах (`deploy/nginx/*.template`) — иначе nginx режет запрос
// раньше, чем он доходит до Next.js, и лимит в коде становится
// недостижимым.
export const MAX_UPLOAD_SIZE = 50 * 1024 * 1024; // 50 МБ

export function formatMaxSize(): string {
  return `${MAX_UPLOAD_SIZE / (1024 * 1024)} МБ`;
}

// Отсечка ДО чтения тела: `file.size` можно проверить только после того, как
// `request.formData()` уже втянул весь multipart в память, то есть проверка
// размера по файлу не спасает от OOM — она срабатывает, когда байты уже
// заняли память. `Content-Length` доступен из заголовков сразу, поэтому
// заведомо большой запрос отклоняется, не будучи прочитанным.
// Запас в 1 МБ — на служебные части multipart (границы, имена полей).
export function exceedsContentLength(request: Request): boolean {
  const raw = request.headers.get("content-length");
  if (!raw) return false;
  const length = Number(raw);
  if (!Number.isFinite(length)) return false;
  return length > MAX_UPLOAD_SIZE + 1024 * 1024;
}
