-- Бесхозные пространства получают владельца — первого администратора.
--
-- Демо-пространства создаются сидом при первом старте контейнера, когда
-- пользователей в базе ещё нет, поэтому ownerId у них остаётся NULL. Из-за
-- этого в них не работает эскалация свежести: когда автор статьи давно не
-- заходил, напоминание уходит владельцу пространства, а его нет — и
-- уведомление не создаётся вовсе.
--
-- Для новых установок это закрыто в самой регистрации (первый
-- зарегистрировавшийся забирает бесхозные пространства себе), а эта миграция
-- чинит уже работающие инстансы, где админ появился раньше этой правки.
--
-- Если администратора ещё нет, UPDATE не тронет ни строки: подзапрос вернёт
-- NULL, а условие EXISTS не выполнится.
UPDATE "Space"
SET "ownerId" = (
  SELECT id FROM "User"
  WHERE role = 'ADMIN' AND status = 'ACTIVE'
  ORDER BY "createdAt" ASC
  LIMIT 1
)
WHERE "ownerId" IS NULL
  AND EXISTS (SELECT 1 FROM "User" WHERE role = 'ADMIN' AND status = 'ACTIVE');
